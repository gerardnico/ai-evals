"""
Run mitmproxy as an embedded library
"""

import asyncio
import socket
import threading
import time

from gerardnico.aitm.context import Context
from gerardnico.aitm.mitm_addon_http_logger import HttpDumper
import secrets
from mitmproxy import options
from mitmproxy.tools.dump import DumpMaster
from mitmproxy.tools.web.master import WebMaster

import platform
from pathlib import Path
import sys
import subprocess


class MitmproxyRunner:
    def __init__(self, context: Context):
        self.host = context.mitm_host
        self.port = context.mitm_port
        self.master = None
        self.thread = None
        self.created = threading.Event()
        self.context = context
        self.start_web_instance = self.context.mitm_web_port is not None and self.context.agent_interactive == True
        # Password values starting with `$` are interpreted as an argon2 hash
        self.web_password = secrets.token_hex(16)
        self.ca_cert_path = Path.home() / ".mitmproxy" / "mitmproxy-ca-cert.pem"

        # Ensure no listening socket
        try:
            with socket.create_connection((self.host, self.port), timeout=0.2):
                raise Exception("Proxy port is already taken")
        except OSError:
            pass

    async def _run_proxy(self):
        """
        Async so that there is a loop
        It's mandatory
        """

        opts = options.Options(
            listen_host=self.host,
            listen_port=self.port,
        )
        # In non-interactive mode, no webui is needed
        if self.start_web_instance:
            self.master = WebMaster(
                opts,
                # don't keep mitmproxy's own startup/log messages
                with_termlog=False
            )
            self.master.options.update(
                web_open_browser=False,
                web_port=self.context.mitm_web_port,
                web_password=self.web_password,
            )
        else:
            self.master = DumpMaster(
                opts,
                # don't keep mitmproxy's own startup/log messages
                with_termlog=False,
                # skips adding the dumper addon that prints request/response info to stdout
                with_dumper=False,
            )
        self.master.addons.add(HttpDumper(self.context.session.http_dump_dir))
        self.created.set()

        await self.master.run()

    def _thread_target(self):
        asyncio.run(self._run_proxy())

    def install_cert_eventually(self):

        # You can't install the cert without the user typing the password for sudo
        if not self.context.agent_interactive:
            return None

        if platform.system() != "Linux":
            print("This script only supports Linux.", file=sys.stderr)
            return None

        # generated by mitmproxy/certs.py
        source = self.ca_cert_path
        target = Path("/usr/local/share/ca-certificates/mitmproxy.crt")

        if not source.exists():
            print(f"Certificate not found: {source}", file=sys.stderr)
            return None

        if target.exists():
            print(f"Cert already installed")
            return None

        print(f"Installation of the proxy cert")
        try:
            subprocess.run(["sudo", "cp", str(source), str(target)], check=True)
            subprocess.run(["sudo", "update-ca-certificates"], check=True)
        except subprocess.CalledProcessError as e:
            print(f"Command failed: {e}", file=sys.stderr)
            return None
        except FileNotFoundError as e:
            print(f"Required command not found (is 'sudo' installed?): {e}", file=sys.stderr)
            return None

        print(f"Installed CA certificate to {target}")
        return None

    def start(self):
        self.thread = threading.Thread(
            target=self._thread_target,
            name="aitm-proxy",
            daemon=True,
        )
        self.thread.start()
        self.created.wait()

        # Ensure mitmproxy has actually bound its listening socket.
        deadline = time.monotonic() + 10
        while time.monotonic() < deadline:
            try:
                with socket.create_connection((self.host, self.port), timeout=0.2):
                    print(f"Aitm Proxy listening on http://{self.host}:{self.port}")
                    if self.start_web_instance:
                        print(
                            f"Aitm Proxy Web at http://{self.host}:{self.context.mitm_web_port}?token={self.web_password}")
                    self.install_cert_eventually()
                    return
            except OSError:
                time.sleep(0.1)

        self.stop()
        raise TimeoutError("Aitm proxy did not start listening")

    def stop(self):

        if self.master is not None:
            self.master.shutdown()

        if self.thread is not None:
            self.thread.join(timeout=5)
